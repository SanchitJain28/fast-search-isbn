import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createServer } from 'vite';
import { PackingStore } from '../server/store.js';
import { packingApiPlugin } from '../server/api.js';

test('station display names persist and broadcast without changing scans, IDs or the Sheets queue', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'isbn-station-names-'));
  const databasePath = path.join(root, 'data/packing.sqlite');
  const catalog = [{ ISBN13: '9781234567890', Order: '317', Title: 'Station test book' }];
  fs.mkdirSync(path.join(root, 'public'));
  fs.writeFileSync(path.join(root, 'public/master.json'), JSON.stringify(catalog));
  const setup = new PackingStore(databasePath, catalog); setup.initializeEmpty(); setup.close();
  const server = await createServer({ configFile: false, root, plugins: [packingApiPlugin(root, { databasePath })], server: { port: 0, host: '127.0.0.1' } });
  await server.listen();
  t.after(async () => { await server.close(); fs.rmSync(root, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.httpServer.address().port}`;
  const send = (route, data, origin = base) => fetch(base + route, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: origin }, body: JSON.stringify(data) });
  const scan = await (await send('/api/scan', { id: 'station-scan', isbn: catalog[0].ISBN13, station: 'Station-fixed-id' })).json();
  const before = await (await fetch(base + '/api/state')).json();
  const controller = new AbortController();
  const events = await fetch(base + '/api/events', { signal: controller.signal });
  const reader = events.body.getReader();
  await reader.read();
  const renamed = await send('/api/station-name', { station: 'Station-fixed-id', name: 'Basement floor' });
  assert.equal(renamed.status, 200);
  const event = new TextDecoder().decode((await reader.read()).value);
  assert.match(event, /STATION_NAMES/); assert.match(event, /Basement floor/);
  controller.abort();
  const after = await (await fetch(base + '/api/state')).json();
  assert.equal(after.stationNames['Station-fixed-id'], 'Basement floor');
  assert.deepEqual(after.scans, before.scans);
  assert.equal(after.mirror.pending, before.mirror.pending);
  assert.equal(scan.station, 'Station-fixed-id');
  const saved = new PackingStore(databasePath, catalog);
  assert.equal(JSON.parse(saved.getMeta('stationDisplayNames'))['Station-fixed-id'], 'Basement floor'); saved.close();
  assert.equal((await send('/api/station-name', { station: 'Station-fixed-id', name: 'Other' }, 'https://untrusted.example')).status, 403);
  assert.equal((await send('/api/station-name', { station: 'Station-fixed-id', name: 'a'.repeat(81) })).status, 400);
  assert.equal((await send('/api/station-name', { station: '__proto__', name: 'Bad' })).status, 400);
  await send('/api/station-name', { station: 'Station-fixed-id', name: '' });
  assert.equal((await (await fetch(base + '/api/state')).json()).stationNames['Station-fixed-id'], undefined);
});
